import assert from 'node:assert/strict';
import fs from 'node:fs';
import {validateMeasuredSeries,sampleByTL,proportionalChange} from '../src/size-series.mjs';
const series=JSON.parse(fs.readFileSync(new URL('../profiles/black_ocellaris_20_35mm.json',import.meta.url),'utf8'));
assert.equal(validateMeasuredSeries(series).length,6);
assert.equal(sampleByTL(series,20).status,'UNSUPPORTED_OUTSIDE_MEASURED_RANGE');
assert.equal(sampleByTL(series,40).status,'UNSUPPORTED_OUTSIDE_MEASURED_RANGE');
const p50=sampleByTL(series,20.82);
assert.equal(p50.status,'FIXED_MEASURED');
assert.equal(p50.bodyWidthMm,7.36);
const p90=sampleByTL(series,31.84);
assert.equal(p90.eyeDiameterMm,2.9);
const mid=sampleByTL(series,(31.84+34.5)/2);
assert.equal(mid.status,'MEASURED_INTERPOLATION');
assert(Math.abs(mid.t-0.5)<1e-12);
assert(Math.abs(mid.bodyWidthMm-(10.37+11.86)/2)<1e-12);
assert(Math.abs(mid.headWidthMm-(8.26+9.36)/2)<1e-12);
const pc=proportionalChange(series);
assert(Math.abs(pc.eyeDiameterPerTL.from-(2.28/20.82))<1e-12);
assert(Math.abs(pc.eyeDiameterPerTL.to-(3.07/34.5))<1e-12);
assert.notEqual(Math.round(pc.bodyWidthPerTL.from*1e6),Math.round(pc.bodyWidthPerTL.to*1e6));
assert.equal(series.crossSourceBridge.toFishBase71mmCard,'CANDIDATE_NEEDS_CALIBRATION_NOT_INTERPOLATABLE_YET');
console.log('Black A. ocellaris 20.82–34.50 mm size series: 12 assertions passed');