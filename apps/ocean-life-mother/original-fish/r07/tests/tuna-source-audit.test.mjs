import assert from 'node:assert/strict';
import {readGlb,auditTunaSource,compareVariants,buildNativeSemanticRig,TUNA_SOURCE_VARIANTS} from '../src/tuna-source-audit.mjs';

const highPath=process.env.TUNA_HIGH;
const lowPath=process.env.TUNA_LOW;
if(!highPath||!lowPath) throw new Error('Set TUNA_HIGH and TUNA_LOW to exact uploaded GLBs');
const high=readGlb(highPath),low=readGlb(lowPath);
assert.equal(high.sha256,TUNA_SOURCE_VARIANTS.high.sha256);
assert.equal(high.bytes.length,TUNA_SOURCE_VARIANTS.high.bytes);
assert.equal(low.sha256,TUNA_SOURCE_VARIANTS.low.sha256);
assert.equal(low.bytes.length,TUNA_SOURCE_VARIANTS.low.bytes);
const comparison=compareVariants(high,low);
assert.equal(comparison.nodesEqual,true);
assert.equal(comparison.meshesEqual,true);
assert.equal(comparison.skinsEqual,true);
assert.equal(comparison.animationsEqual,true);
assert.equal(comparison.materialsEqual,true);
assert.equal(comparison.geometryRigAnimationArraysExactlyEqual,true);
assert.equal(comparison.equalAccessors,603);
assert.equal(comparison.maxAccessorDiff,0);
const audit=auditTunaSource(high);
assert.equal(audit.counts.nodes,113);
assert.equal(audit.counts.meshes,3);
assert.equal(audit.counts.joints,98);
assert.equal(audit.counts.animations,1);
assert.equal(audit.counts.animationChannels,291);
assert.equal(audit.counts.images,6);
assert.equal(audit.animation.name,'Swim');
assert(Math.abs(audit.animation.durationSeconds-2.1666667461395264)<1e-6);
assert.equal(audit.animation.animatedNodeCount,97);
assert.equal(audit.animation.animatedJointCount,97);
assert.equal(audit.animation.pathCounts.rotation,97);
assert.equal(audit.animation.pathCounts.translation,97);
assert.equal(audit.animation.pathCounts.scale,97);
assert(audit.animation.significantRotationCount>=68);
assert.equal(audit.animation.significantTranslationCount,4);
assert.equal(audit.animation.significantScaleCount,0);
assert.equal(audit.materials[2].alphaMode,'BLEND');
assert(Math.abs(audit.materials[2].baseColorAlpha-0.028952469188477523)<1e-12);
const rig=buildNativeSemanticRig(high);
assert.equal(rig.sourceJointCount,98);
assert.equal(rig.nativeControlCount,24);
assert(rig.compression.mergedCenterDistance<1e-12);
assert.equal(rig.sourceRuntimeDependency,false);
assert.equal(rig.acceptance.productionReady,false);
console.log(JSON.stringify({comparison,audit:{counts:audit.counts,animation:audit.animation,materials:audit.materials},rig:{nativeControlCount:rig.nativeControlCount,compression:rig.compression}},null,2));
console.log('Original Fish R07 tuna source audit: 32 assertions passed');
