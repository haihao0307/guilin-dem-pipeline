import assert from 'node:assert/strict';
import fs from 'node:fs';
const root=new URL('./../',import.meta.url);
const read=p=>JSON.parse(fs.readFileSync(new URL(p,root),'utf8'));
const gate=read('SOURCE_COPY_UNLOCK_GATE_R001.json');
const blueprint=read('SOURCE_COPY_BLUEPRINT_R001.json');
const conflict=read('SOURCE_VS_YELLOWFIN_CONFLICT_R002.json');
const render=read('SOURCE_RENDER_HIGHRES_OBSERVATION_R003.json');
const py=fs.readFileSync(new URL('tools/extract_yellowfin_copy_evidence.py',root),'utf8');
let n=0;const ok=(v,m)=>{assert(v,m);n++};
ok(gate.generationLocked===true,'generation locked');
ok(gate.sourceCopyUnlocked===false,'source copy locked');
ok(gate.checks.exactSourceBinaryAvailable===false,'exact binary absent');
ok(gate.checks.visibleDorsalFinletCount===8,'dorsal visible count');
ok(gate.checks.visibleVentralFinletCount===7,'ventral visible count');
ok(blueprint.copyPrinciple.includes('copy source first'),'copy-first principle');
ok(blueprint.hardFails.includes('placeholder finlets'),'placeholder finlets prohibited');
ok(render.directVisualCounts.threeDimensionalVerificationPending===true,'3D finlet verification open');
ok(conflict.workflowRule.includes('copies the source'),'source/species phases separated');
ok(py.includes('exact FISH-REF-002 required'),'extractor exact-hash guard');
ok(py.includes('sourceCopyGeometryGenerated'), 'extractor evidence-only boundary');
ok(py.includes('peduncle_scan'), 'peduncle evidence extractor present');
ok(py.includes('components_for_group'), 'connected component extractor present');
ok(!fs.existsSync(new URL('../yellowfin-source-copy-r001/SOURCE_COPY_GEOMETRY.glb',root)),'no premature geometry');
console.log(`Yellowfin R006 gate: ${n} assertions passed`);
